#!/usr/bin/env python3
"""Differential harness: pinned C oracle vs candidate, byte-for-byte.

Wayfinder ticket #13: Differential oracle harness and byte-parity corpus.
Issue #66 adds the stdout gate: the candidate's captured stdout is compared
byte-for-byte against the oracle's captured stdout on every corpus run, as an
additional gate field next to the output-file parity gate.

The byte-identity gate from the port strategy (ADR docs/adr/0001-port-strategy.md,
closed ticket #6) is binding: a candidate (the Rust port under stage-1
verification, an idiomatization rung, or the serial-path CI gate) must produce
byte-identical output files to the pinned C oracle over the full corpus.

Modes
  self-check (default, no --candidate)
      1. verify the corpus regenerates byte-identically (generator determinism),
      2. run the oracle over the corpus and verify non-empty, sane outputs,
      3. re-run the oracle and assert byte-identical self-determinism
         (output files and captured stdout),
      4. wire the stub (tools/oracle/stub_candidate.py) as a candidate and
         demonstrate that an injected trivial divergence is DETECTED and
         LOCALIZED exactly (input, option flags, output file, first differing
         line), end to end.
      Exit 0 iff every phase holds.
  differential (--candidate PATH)
      Run the candidate executable over the corpus and compare every expected
      output file byte-for-byte against the (cached) oracle outputs, and the
      candidate's captured stdout byte-for-byte against the oracle's captured
      stdout of the same run (the stdout gate, issue #66). On mismatch,
      report enough to bisect against the strict function-per-function mapping:
      which case (and its kind/size), which option flag string, which output
      file (or the stdout stream), the first differing byte offset and line,
      both diverging lines, and the surrounding context.

Candidate contract
  The candidate must be an executable with the triangle-CLI interface: invoked
  as './candidate [options...] <input>' inside a fresh run directory that
  already contains the input files, it must exit 0 and write the outputs with
  the standard names ('input.1.node', 'input.1.ele', ...). The harness always
  invokes both oracle and candidate through a symlink named 'candidate' so the
  '# Generated by ...' trailer line embedded by the file writers matches
  byte-for-byte. The environment variables ORACLE_HARNESS_CASE and
  ORACLE_HARNESS_FAMILY identify the current run to the candidate (used by
  the stub; a real candidate ignores them).

Usage:
  python3 tools/oracle/diff_harness.py                         # self-check
  python3 tools/oracle/diff_harness.py --candidate BIN        # differential run
Options: --case GLOB --family GLOB (fnmatch filters), --report PATH (JSON report).
"""

import argparse
import fnmatch
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(SCRIPT_DIR, "work")
DEFAULT_ORACLE = os.path.join(WORK, "oracle", "triangle-oracle")
DEFAULT_CORPUS = os.path.join(WORK, "corpus")
GENERATOR = os.path.join(SCRIPT_DIR, "generate_corpus.py")

# Injected-divergence spec used by the self-check (see also stub_candidate.py):
# one value (vertex coordinate) in one output file of one corpus run.
STUB_PERTURB = {"case": "random_m", "family": "pq20", "file": "input.1.node",
                "line": 6, "field": 1, "delta": 1e-9, "mode": "perturb"}
# Second demo: a missing expected output file.
STUB_DROP = {"case": "grid_s", "family": "p", "file": "input.1.ele", "mode": "drop"}

CONTEXT = 3  # lines of context around a first divergence


def log(msg):
    sys.stdout.write(msg + "\n")
    sys.stdout.flush()


def fail(msg):
    sys.stdout.write("[harness] FAIL: %s\n" % msg)
    sys.stdout.flush()


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def load_manifest(corpus_dir):
    with open(os.path.join(corpus_dir, "manifest.json")) as f:
        manifest = json.load(f)
    if manifest.get("manifest_version") != 1:
        raise RuntimeError("unsupported manifest version in %s" % corpus_dir)
    return manifest


def run_entries(manifest, case_filter, family_filter):
    for case in manifest["cases"]:
        if case_filter and not fnmatch.fnmatchcase(case["id"], case_filter):
            continue
        for family in case["families"]:
            if family_filter and not fnmatch.fnmatchcase(family["tag"], family_filter):
                continue
            yield case, family


def run_tool(tool, run_dir, argv, env_extra):
    """Materialize the input, symlink the tool as ./candidate, run it."""
    if not os.path.isfile(os.path.join(run_dir, "candidate")):
        os.symlink(os.path.abspath(tool), os.path.join(run_dir, "candidate"))
    with open(os.path.join(run_dir, "candidate-stdout.txt"), "wb") as out:
        env = dict(os.environ)
        env.update(env_extra)
        return subprocess.run(["./candidate"] + argv, cwd=run_dir,
                              stdout=out, stderr=subprocess.STDOUT, env=env)


def prepare_run_dir(bases, case, family, corpus_dir):
    path = os.path.join(bases, case["id"], family["tag"])
    if os.path.exists(path):
        shutil.rmtree(path)
    os.makedirs(path)
    shutil.copy(os.path.join(corpus_dir, case["id"], family["input"]),
                os.path.join(path, family["input"]))
    return path


def expected_paths(family):
    base = "input.1."
    return [base + ext for ext in family["expected"]]


def oracle_run(oracle, cache_root, oracle_key, case, family, corpus_dir):
    """Run the oracle for one entry, using and populating the cache."""
    cache_dir = os.path.join(cache_root, oracle_key, case["id"], family["tag"])
    done_marker = os.path.join(cache_dir, ".complete")
    if os.path.exists(done_marker):
        return cache_dir, None
    # cache dirs are reused as run dirs (one run per dir)
    if os.path.exists(cache_dir):
        shutil.rmtree(cache_dir)
    os.makedirs(cache_dir)
    shutil.copy(os.path.join(corpus_dir, case["id"], family["input"]),
                os.path.join(cache_dir, family["input"]))
    env = {"ORACLE_HARNESS_CASE": case["id"], "ORACLE_HARNESS_FAMILY": family["tag"]}
    proc = run_tool(oracle, cache_dir, family["argv"], env)
    if proc.returncode != 0:
        return cache_dir, "oracle exited %d (case %s, family %s)" % (
            proc.returncode, case["id"], family["tag"])
    for name in expected_paths(family):
        p = os.path.join(cache_dir, name)
        if not os.path.isfile(p) or os.path.getsize(p) == 0:
            return cache_dir, "oracle did not produce non-empty %s (case %s, family %s)" % (
                name, case["id"], family["tag"])
    sanity = check_sane(cache_dir, family)
    if sanity:
        return cache_dir, "oracle output sanity: %s (case %s, family %s)" % (
            sanity, case["id"], family["tag"])
    with open(done_marker, "w") as f:
        f.write("ok\n")
    return cache_dir, None


def check_sane(run_dir, family):
    """Sanity thresholds for oracle outputs: counts must be positive."""
    node = os.path.join(run_dir, "input.1.node")
    if os.path.isfile(node):
        first = open(node).readline().split()
        if len(first) >= 4 and int(float(first[0])) <= 0:
            return "node file has no vertices"
    ele = os.path.join(run_dir, "input.1.ele")
    if os.path.isfile(ele):
        first = open(ele).readline().split()
        if len(first) >= 3 and int(float(first[0])) <= 0:
            return "ele file has no triangles"
    return None


def first_diff(oracle_path, cand_path):
    """Return a dict describing the first byte divergence between two files."""
    with open(oracle_path, "rb") as f:
        a = f.read()
    with open(cand_path, "rb") as f:
        b = f.read()
    if a == b:
        return None
    common = min(len(a), len(b))
    for i in range(common):
        if a[i] != b[i]:
            break
    else:
        i = common
    a_text = a.decode("latin-1")
    b_text = b.decode("latin-1")
    a_lines = a_text.split("\n")
    b_lines = b_text.split("\n")
    line_no = a_text[:i].count("\n") + 1
    # byte index of the line start
    line_start = 0
    for k in range(line_no - 1):
        line_start = a_text.index("\n", line_start) + 1
    col = i - line_start + 1

    def snap(lines, no):
        lo = max(0, no - 1 - CONTEXT)
        hi = min(len(lines), no - 1 + CONTEXT + 1)
        return ["%5d: %s" % (lo + j + 1, lines[lo + j]) for j in range(hi - lo)]

    kind = "byte_diff"
    if i >= len(a) and len(a) < len(b):
        kind = "candidate_longer"
    elif i >= len(b) and len(b) < len(a):
        kind = "oracle_longer"
    result = {
        "status": kind,
        "byte_offset": i,
        "line": line_no,
        "column": col,
        "oracle_size": len(a),
        "candidate_size": len(b),
        "oracle_line": a_lines[line_no - 1] if line_no - 1 < len(a_lines) else "<eof>",
        "candidate_line": b_lines[line_no - 1] if line_no - 1 < len(b_lines) else "<eof>",
        "oracle_context": snap(a_lines, line_no),
        "candidate_context": snap(b_lines, line_no),
    }
    return result


def compare_entry(oracle_dir, cand_dir, case, family):
    """Compare all expected outputs; return a list of mismatch entries."""
    mismatches = []
    for name in expected_paths(family):
        cand_path = os.path.join(cand_dir, name)
        if not os.path.isfile(cand_path):
            mismatches.append({
                "case": case["id"], "kind": case["kind"], "size": case["size"],
                "family": family["tag"], "options": family["options"],
                "input": family["input"], "file": name,
                "status": "missing_output",
                "detail": "expected output %s was not produced" % name,
            })
            continue
        diff = first_diff(os.path.join(oracle_dir, name), cand_path)
        if diff:
            mismatches.append({
                "case": case["id"], "kind": case["kind"], "size": case["size"],
                "family": family["tag"], "options": family["options"],
                "input": family["input"], "file": name,
                **diff,
            })
    # The stdout gate (issue #66): the candidate's captured stdout against
    # the oracle's captured stdout of the same corpus run, byte-for-byte,
    # localized with the same first-difference report. run_tool folds stderr
    # into the capture for both tools, so the gate covers the merged
    # terminal stream exactly as each tool wrote it. All current corpus
    # families are non-verbose, so the registered D33 verbose divergence
    # stays untouched by this gate.
    oracle_stdout = os.path.join(oracle_dir, "candidate-stdout.txt")
    cand_stdout = os.path.join(cand_dir, "candidate-stdout.txt")
    if not (os.path.isfile(oracle_stdout) and os.path.isfile(cand_stdout)):
        mismatches.append({
            "case": case["id"], "kind": case["kind"], "size": case["size"],
            "family": family["tag"], "options": family["options"],
            "input": family["input"], "file": "stdout",
            "status": "missing_output",
            "detail": "stdout capture missing (oracle: %s, candidate: %s)"
                      % (os.path.isfile(oracle_stdout),
                         os.path.isfile(cand_stdout)),
        })
    else:
        diff = first_diff(oracle_stdout, cand_stdout)
        if diff:
            mismatches.append({
                "case": case["id"], "kind": case["kind"], "size": case["size"],
                "family": family["tag"], "options": family["options"],
                "input": family["input"], "file": "stdout",
                **diff,
            })
    return mismatches


def print_mismatch(m, index):
    bar = "-" * 72
    log(bar)
    log("MISMATCH %d" % index)
    log("  case:       %s (kind %s, size %s)" % (m["case"], m.get("kind"), m.get("size")))
    log("  family:     %s (options: %s, input file: %s)"
        % (m["family"], m["options"] or "<none>", m["input"]))
    log("  output:     %s" % m["file"])
    if m["status"] == "missing_output":
        log("  status:     %s" % m["status"])
        log("  detail:     %s" % m["detail"])
    else:
        log("  status:     %s" % m["status"])
        log("  first diff: byte %d, line %d, column %d (oracle %d bytes, candidate %d bytes)"
            % (m["byte_offset"], m["line"], m["column"],
               m["oracle_size"], m["candidate_size"]))
        log("  oracle line:     %s" % m["oracle_line"])
        log("  candidate line: %s" % m["candidate_line"])
        log("  oracle context:")
        for ln in m["oracle_context"]:
            log("    %s" % ln)
        log("  candidate context:")
        for ln in m["candidate_context"]:
            log("    %s" % ln)
    log(bar)


def cache_key(oracle):
    return sha256_file(oracle)[:12]


def self_check(args, manifest):
    log("=== harness self-check ===")
    ok = True
    entries = list(run_entries(manifest, args.case, args.family))

    # --- 1. corpus regeneration determinism --------------------------------
    tmp = os.path.join(WORK, "corpus-regen-check")
    if os.path.exists(tmp):
        shutil.rmtree(tmp)
    proc = subprocess.run([sys.executable, GENERATOR, "--out", tmp, "--quiet"],
                          capture_output=True)
    if proc.returncode != 0:
        fail("corpus generation failed:\n%s" % proc.stderr.decode())
        return 1
    regen_ok = True
    for case in manifest["cases"]:
        for key in ("node", "poly"):
            src = os.path.join(tmp, case["id"], case["input"][key]["file"])
            want = case["input"][key]["sha256"]
            if sha256_file(src) != want:
                fail("regenerated %s/input.%s does not match the manifest hash"
                     % (case["id"], key))
                regen_ok = False
    shutil.rmtree(tmp)
    if regen_ok:
        log("[ok] corpus regeneration byte-identical for all %d cases"
            % len(manifest["cases"]))

    # --- 2+3. oracle pass and self-determinism -----------------------------
    cache_root = os.path.join(WORK, "cache")
    key = cache_key(args.oracle)
    passes = []
    for label in ("pass1", "pass2"):
        run_base = os.path.join(WORK, "selfcheck-%s" % label)
        if os.path.exists(run_base):
            shutil.rmtree(run_base)
        os.makedirs(run_base)
        mismatches = []
        problems = []
        for case, family in entries:
            if label == "pass1":
                _, problem = oracle_run(args.oracle, cache_root, key, case, family,
                                        args.corpus)
                if problem:
                    problems.append(problem)
            else:
                # fresh run dir per entry (no cache), contract identical
                run_dir = prepare_run_dir(run_base, case, family, args.corpus)
                env = {"ORACLE_HARNESS_CASE": case["id"],
                       "ORACLE_HARNESS_FAMILY": family["tag"]}
                proc = run_tool(args.oracle, run_dir, family["argv"], env)
                if proc.returncode != 0:
                    problems.append("oracle exited %d (case %s, family %s)"
                                    % (proc.returncode, case["id"], family["tag"]))
                    continue
                oracle_dir = os.path.join(cache_root, key, case["id"], family["tag"])
                mismatches += compare_entry(oracle_dir, run_dir, case, family)
        if problems:
            for p in problems:
                fail(p)
            ok = False
            continue
        passes.append((label, mismatches))

    if ok and len(passes) == 2:
        ident = len(passes[1][1]) == 0
        log("[%s] oracle self-determinism: pass2 vs cached pass1 byte-identical for all %d runs"
            % ("ok" if ident else "FAIL", len(entries)))
        if not ident:
            for m in passes[1][1][:10]:
                print_mismatch(m, 0)
            ok = False
    else:
        log("[FAIL] oracle passes did not complete")
        ok = False

    # --- 4. stub demo: injected divergence ----------------------------------
    if not any(c["id"] == STUB_PERTURB["case"] for c in manifest["cases"]) or \
       not any(c["id"] == STUB_DROP["case"] for c in manifest["cases"]):
        if args.case or args.family:
            log("[info] --case/--family filters exclude the stub demo targets; "
                "run without filters for the full self-check")

    stub = os.path.join(SCRIPT_DIR, "stub_candidate.py")
    for spec in (STUB_PERTURB, STUB_DROP):
        if args.case and not fnmatch.fnmatchcase(spec["case"], args.case):
            continue
        if args.family and not fnmatch.fnmatchcase(spec["family"], args.family):
            continue
        target_case = next(c for c in manifest["cases"] if c["id"] == spec["case"])
        target_family = next(f for f in target_case["families"]
                             if f["tag"] == spec["family"])
        expected = mismatches_for_stub(args, manifest, spec, stub, cache_root, key,
                                       target_case, target_family)
        # demo 1: exactly one byte-diff mismatch, localized at the spec
        # demo 2: exactly one missing-output mismatch at the spec file
        filtered = [m for m in expected
                    if m["case"] == spec["case"] and m["family"] == spec["family"]]
        others = [m for m in expected if m not in filtered]
        hit = filtered if len(filtered) == 1 and not others else None
        if spec["mode"] == "perturb":
            if hit and hit[0]["status"] == "byte_diff" and hit[0]["file"] == spec["file"] \
               and hit[0]["line"] == spec["line"]:
                log("[ok] injected divergence detected and localized: case %s, family %s, "
                    "file %s, first differing line %d"
                    % (spec["case"], spec["family"], spec["file"], spec["line"]))
                print_mismatch(hit[0], 1)
            else:
                fail("injected divergence not detected/localized as spec'd "
                     "(case %s, family %s); got: %s"
                     % (spec["case"], spec["family"],
                        json.dumps(expected, default=str)[:600]
                        if expected else "no mismatch"))
                ok = False
        else:
            if hit and hit[0]["status"] == "missing_output" and hit[0]["file"] == spec["file"]:
                log("[ok] missing-output divergence detected: case %s, family %s, "
                    "file %s missing" % (spec["case"], spec["family"], spec["file"]))
                print_mismatch(hit[0], 2)
            else:
                fail("missing-output divergence not detected as spec'd")
                ok = False

    # --- stats ---------------------------------------------------------------
    total_out = 0
    max_run = None
    for case, family in entries:
        d = os.path.join(cache_root, key, case["id"], family["tag"])
        if not os.path.isdir(d):
            continue
        size = sum(os.path.getsize(os.path.join(d, n))
                   for n in os.listdir(d) if os.path.isfile(os.path.join(d, n)))
        total_out += size
        if max_run is None or size > max_run[2]:
            max_run = (case["id"], family["tag"], size)
    log("=== corpus stats ===")
    log("  cases: %d  runs (case x family): %d" % (len(manifest["cases"]), len(entries)))
    log("  total oracle output bytes (cached): %d" % total_out)
    if max_run:
        log("  largest run: %s/%s (%d bytes of outputs)" % max_run)
    log("=== self-check %s ===" % ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


def mismatches_for_stub(args, manifest, spec, stub, cache_root, key,
                        target_case, target_family):
    """Run the stub as candidate over the scope and return mismatches."""
    mismatches = []
    for case, family in run_entries(manifest, args.case, args.family):
        if spec["mode"] == "perturb":
            env = {
                "ORACLE_HARNESS_CASE": case["id"],
                "ORACLE_HARNESS_FAMILY": family["tag"],
                "STUB_BIN": os.path.abspath(args.oracle),
                "STUB_MODE": "perturb",
                "STUB_CASE": spec["case"],
                "STUB_FAMILY": spec["family"],
                "STUB_FILE": spec["file"],
                "STUB_LINE": str(spec["line"]),
                "STUB_FIELD": str(spec["field"]),
                "STUB_DELTA": repr(spec["delta"]),
            }
        else:
            env = {
                "ORACLE_HARNESS_CASE": case["id"],
                "ORACLE_HARNESS_FAMILY": family["tag"],
                "STUB_BIN": os.path.abspath(args.oracle),
                "STUB_MODE": "drop",
                "STUB_CASE": spec["case"],
                "STUB_FAMILY": spec["family"],
                "STUB_FILE": spec["file"],
            }
        run_dir = prepare_run_dir(os.path.join(WORK, "stub-runs"), case,
                                  family, args.corpus)
        proc = run_tool(stub, run_dir, family["argv"], env)
        if proc.returncode != 0:
            mismatches.append({
                "case": case["id"], "kind": case["kind"], "size": case["size"],
                "family": family["tag"], "options": family["options"],
                "input": family["input"], "file": "<run>",
                "status": "candidate_exit_%d" % proc.returncode,
                "detail": "stub exited %d" % proc.returncode,
            })
            continue
        oracle_dir = os.path.join(cache_root, key, case["id"], family["tag"])
        mismatches += compare_entry(oracle_dir, run_dir, case, family)
    return mismatches


def differential(args, manifest):
    entries = list(run_entries(manifest, args.case, args.family))
    cache_root = os.path.join(WORK, "cache")
    key = cache_key(args.oracle)
    run_base = os.path.join(WORK, "runs", key)
    log("=== differential run: %d entries, candidate %s ==="
        % (len(entries), args.candidate))
    mismatches = []
    t0 = time.time()
    for index, (case, family) in enumerate(entries, 1):
        oracle_dir, problem = oracle_run(args.oracle, cache_root, key, case, family,
                                         args.corpus)
        if problem:
            fail(problem)
            return 2
        run_dir = prepare_run_dir(run_base, case, family, args.corpus)
        env = {"ORACLE_HARNESS_CASE": case["id"],
               "ORACLE_HARNESS_FAMILY": family["tag"]}
        proc = run_tool(args.candidate, run_dir, family["argv"], env)
        if proc.returncode != 0:
            mismatches.append({
                "case": case["id"], "kind": case["kind"], "size": case["size"],
                "family": family["tag"], "options": family["options"],
                "input": family["input"], "file": "<run>",
                "status": "candidate_exit_%d" % proc.returncode,
                "detail": "candidate exited %d; see %s" % (
                    proc.returncode, os.path.join(run_dir, "candidate-stdout.txt")),
            })
            continue
        mismatches += compare_entry(oracle_dir, run_dir, case, family)
        if index % 10 == 0:
            log("  ... %d/%d runs compared" % (index, len(entries)))
        # keep the run dir only for the last few runs to bound the work dir
        shutil.rmtree(run_dir, ignore_errors=True)
    elapsed = time.time() - t0
    log("=== differential run finished in %.1fs ===" % elapsed)
    for i, m in enumerate(mismatches[:10], 1):
        print_mismatch(m, i)
    if len(mismatches) > 10:
        log("... and %d further mismatches (see the JSON report)" % (len(mismatches) - 10))
    stdout_mismatches = sum(1 for m in mismatches if m.get("file") == "stdout")
    report = {
        "mode": "differential",
        "candidate": os.path.abspath(args.candidate),
        "oracle": os.path.abspath(args.oracle),
        "oracle_sha256": sha256_file(args.oracle),
        "corpus": os.path.abspath(args.corpus),
        "entries": len(entries),
        "mismatches": mismatches,
        "byte_identical": len(mismatches) == 0,
        "stdout_identical": stdout_mismatches == 0,
    }
    write_report(args, report)
    if mismatches:
        log("RESULT: %d mismatching outputs over %d runs (%d stdout); see the JSON report."
            % (len(mismatches), len(entries), stdout_mismatches))
        return 1
    log("RESULT: all %d runs byte-identical and stdout-identical." % len(entries))
    return 0


def write_report(args, report):
    path = args.report or os.path.join(WORK, "reports", "last-run.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(report, f, indent=2, sort_keys=True)
        f.write("\n")
    log("report written: %s" % path)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--candidate", default=None,
                        help="candidate executable with the triangle-CLI interface")
    parser.add_argument("--oracle", default=DEFAULT_ORACLE)
    parser.add_argument("--corpus", default=DEFAULT_CORPUS)
    parser.add_argument("--case", default=None, help="fnmatch filter on case ids")
    parser.add_argument("--family", default=None, help="fnmatch filter on family tags")
    parser.add_argument("--report", default=None, help="JSON report path")
    args = parser.parse_args()

    if not os.path.isfile(args.oracle):
        sys.stderr.write("oracle binary not found at %s - run tools/oracle/build-oracle.sh\n"
                         % args.oracle)
        return 2
    if not os.path.isfile(os.path.join(args.corpus, "manifest.json")):
        sys.stderr.write("corpus manifest not found in %s - run "
                         "tools/oracle/generate_corpus.py\n" % args.corpus)
        return 2
    manifest = load_manifest(args.corpus)

    if args.candidate:
        return differential(args, manifest)
    return self_check(args, manifest)


