#!/usr/bin/env python3
"""Injected-divergence stub for the differential harness (wayfinder #13).

The harness is validated end to end against a trivially diverging candidate:
this stub behaves like a byte-perfect port (it runs the real oracle and passes
its argv through EXACTLY, including argv[0], so even the '# Generated by ...'
trailer matches the oracle), then injects a single divergence into one output
file of one designated corpus run. The harness must detect and localize it.

Environment (set by tools/oracle/diff_harness.py, or by hand for demos):
  STUB_BIN      required: path to the pinned oracle binary
  STUB_CASE     target case id (e.g. random_m)
  STUB_FAMILY   target option family tag (e.g. pq20)
  STUB_MODE     perturb (default: change one value) | drop (delete one file)
  STUB_FILE     output file to corrupt/delete (default input.1.node)
  STUB_LINE     1-based line to corrupt in perturb mode (default 6)
  STUB_FIELD    0-based whitespace-separated field index (default 1)
  STUB_DELTA    numeric delta added to the field value (default 1e-9)

The stub only perturbs the run whose ORACLE_HARNESS_CASE / ORACLE_HARNESS_FAMILY
match STUB_CASE / STUB_FAMILY; every other run is pure passthrough, so a full
corpus sweep produces exactly one divergence.
"""

import os
import re
import subprocess
import sys


def main():
    bin_path = os.environ.get("STUB_BIN")
    if not bin_path:
        sys.stderr.write("stub_candidate.py: STUB_BIN env required\n")
        return 2
    if not os.path.isfile(bin_path):
        sys.stderr.write("stub_candidate.py: STUB_BIN not found: %s\n" % bin_path)
        return 2

    # Run the real oracle with argv passed through unchanged (including
    # argv[0] == './candidate'), so the output headers match the oracle byte
    # for byte before the injected divergence.
    rc = subprocess.call(list(sys.argv), executable=bin_path)
    if rc != 0:
        return rc

    case = os.environ.get("ORACLE_HARNESS_CASE")
    family = os.environ.get("ORACLE_HARNESS_FAMILY")
    want_case = os.environ.get("STUB_CASE", "")
    want_family = os.environ.get("STUB_FAMILY", "")
    if want_case and case != want_case:
        return rc
    if want_family and family != want_family:
        return rc
    if not want_case and not want_family:
        # No target configured: pure passthrough, never perturb.
        return rc

    mode = os.environ.get("STUB_MODE", "perturb")
    target = os.environ.get("STUB_FILE", "input.1.node")

    if mode == "drop":
        if os.path.isfile(target):
            os.remove(target)
        return rc

    line_no = int(os.environ.get("STUB_LINE", "6"))
    field = int(os.environ.get("STUB_FIELD", "1"))
    delta = float(os.environ.get("STUB_DELTA", "1e-9"))

    with open(target, "rb") as f:
        data = f.read()
    lines = data.decode("latin-1").split("\n")
    if line_no < 1 or line_no > len(lines):
        sys.stderr.write("stub_candidate.py: no line %d in %s\n" % (line_no, target))
        return 3
    text = lines[line_no - 1]
    matches = list(re.finditer(r"\S+", text))
    if field >= len(matches):
        sys.stderr.write("stub_candidate.py: no field %d in %s line %d\n"
                         % (field, target, line_no))
        return 3
    m = matches[field]
    old = m.group(0)
    try:
        new = "%.17g" % (float(old) + delta)
    except ValueError:
        sys.stderr.write("stub_candidate.py: field %d in %s line %d is not numeric\n"
                         % (field, target, line_no))
        return 3
    lines[line_no - 1] = text[:m.start()] + new + text[m.end():]
    with open(target, "wb") as f:
        f.write("\n".join(lines).encode("latin-1"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
